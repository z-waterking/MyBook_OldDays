function applyEditorialProfile(dirName, body) {
  const profile = editorialProfiles.get(dirName);
  if (!profile) return body;
  let paragraphs = body.split(/\n{2,}/).map((paragraph) => paragraph.trim()).filter(Boolean);
  if (profile.drop?.length) paragraphs = paragraphs.filter((paragraph) => !profile.drop.some((pattern) => pattern.test(paragraph)));
  let next = paragraphs.join('\n\n');
  for (const [pattern, replacement] of profile.replace || []) next = next.replace(pattern, replacement);
  paragraphs = next.split(/\n{2,}/).map((paragraph) => paragraph.trim()).filter(Boolean);
  for (const [heading, marker] of profile.sections || []) {
    const index = paragraphs.findIndex((paragraph) => {
      marker.lastIndex = 0;
      return marker.test(paragraph);
    });
    if (index >= 0 && !paragraphs[index].startsWith('## ')) {
      paragraphs[index] = '## ' + heading + '\n\n' + paragraphs[index];
    }
  }
  next = paragraphs.join('\n\n');
  return profile.closing ? next.trim() + '\n\n' + profile.closing : next.trim();
}

function buildDraft({ dirName, meta, cleanBody }) {
  const title = titleWithoutPrefix(dirName, meta.title);
  if (customBodies.has(dirName)) {
    return rebaseImages(customBodies.get(dirName)({ dirName, meta, cleanBody }), dirName);
  }
  const body = rebaseImages(cleanBody, dirName).replace(/\n{3,}/g, '\n\n').trim();
  if (editorialProfiles.has(dirName)) return applyEditorialProfile(dirName, body);
  const closing = generateClosing(dirName, title);
  return closing ? `${body}\n\n${closing}` : body;
}

